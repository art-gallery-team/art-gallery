export function getLocalizedLot(lot: Lot): LotLocalizedFields {
  const lang = getSavedLanguage();
  if (lang === 'en' || !lotDictionary[lot.title]) {
    return {
      title: lot.title,
      author: lot.author,
      style: lot.style,
      description: lot.description,
    };
  }
  return lotDictionary[lot.title][lang];
}
